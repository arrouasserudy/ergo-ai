const DIMENSIONS = [
  { id: "space", title: "התנהלות במרחב", factors: ["grossMotor", "interests"] },
  { id: "materials", title: "התנהלות עם חומרים", factors: ["manipulation", "construction", "purpose", "attention"] },
  { id: "pretense", title: "העמדת פנים / משחק סימבולי", factors: ["imitation", "dramatization"] },
  { id: "participation", title: "השתתפות", factors: ["type", "cooperation", "humor", "language"] },
] as const;

function factor(id: string): LevelItem {
  return {
    kind: "level",
    id,
    text: FACTOR_NAMES[id],
    levels: LEVELS.map((value) => ({
      value,
      label: `${value - 6}–${value} חודשים`,
      descriptors: DESCRIPTORS[id][value].map((text, i) => ({ id: `${id}-${value}-${i + 1}`, text })),
    })),
  };
}

const monthsRow = (id: string, label: string, value: number | null, missing = 0): ScoreRow => ({ id, label, value: round1(value), unit: "months", missing });

export const knoxPreschoolPlayScale: AssessmentDefinition = {
  id: "knox-preschool-play-scale",
  version: 1,
  name: "Revised Knox Preschool Play Scale",
  shortName: "Knox",
  summaryGroup: "overall",
  language: "he",
  respondents: ["therapist"],
  ageRange: { minMonths: 0, maxMonths: 36 },
  instructions: [
    "ביחס לכל גורם יש לסמן כל התנהגות שנצפתה. לאחר מכן, יש לדרג את הגורם בעמודה הגילאית שבה מופיעים מרב הסימונים.",
    "במידה והילד פועל פחות מדקה ביחס לתיאור המצוין, או שההתנהגות שמפגין נראית מקרית – לא ניתן ציון.",
    "הציון ניתן לפי הדירוג הגבוה בטווח, למשל: 6-12 חודשים יירשם כ-12 חודשים.",
  ].join("\n"),
  sections: DIMENSIONS.map((d) => ({ id: d.id, title: d.title, items: d.factors.map(factor) })),

  score(answers, { ageMonths }) {
    const value = (id: string) => answers.values[id] ?? null;
    // Unrounded means feed the overall age; rows show one decimal.
    const dimensionMeans = DIMENSIONS.map((d) => meanOf(d.factors.map(value)));
    const dimensions = DIMENSIONS.map((d, i) => monthsRow(d.id, d.title, dimensionMeans[i], d.factors.filter((id) => value(id) === null).length));
    const factors = DIMENSIONS.flatMap((d) => d.factors);
    const factorValues = factors.map(value);
    const missing = factorValues.filter((v) => v === null).length;
    return [
      { id: "factors", title: "ציוני הגורמים", rows: factors.map((id) => monthsRow(id, FACTOR_NAMES[id], value(id), value(id) === null ? 1 : 0)) },
      { id: "dimensions", title: "ציוני המימדים", rows: dimensions },
      {
        id: "overall",
        title: "גיל משחק כולל",
        rows: [
          monthsRow("playAgeDimensions", "ממוצע ציוני המימדים", meanOf(dimensionMeans), missing),
          monthsRow("playAgeFactors", "ממוצע 12 הגורמים", meanOf(factorValues), missing),
          ...(ageMonths === null ? [] : [monthsRow("chronologicalAge", "גיל כרונולוגי", ageMonths)]),
        ],
      },
    ];
  },
};
